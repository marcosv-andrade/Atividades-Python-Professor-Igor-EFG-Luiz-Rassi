# 14. Verificador de Número Positivo: Escreva um código que diga se um número
# digitado é positivo, negativo ou zero.

numero = int(input("Digite um numero: "))

if numero > 0:
    print(f"o numero é positivo")
elif numero < 0:
    print(f"o numero é negativo")
else:
    print(f'o numero é 0')
             

    